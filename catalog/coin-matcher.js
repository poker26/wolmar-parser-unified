// Металл, названный в самом лоте: «Au 15,5», «Ag», «серебро 925». Возвращаем проверку для
// coin_type.metal, где он записан по-русски или по-английски.
const LOT_METAL = [
  [/золот|(?<![а-яёa-z])au(?![а-яёa-z])/i, /золот|gold/i],
  [/сереб|(?<![а-яёa-z])ag(?![а-яёa-z])/i, /сереб|silver/i],
  [/платин|(?<![а-яёa-z])pt(?![а-яёa-z])/i, /платин|platin/i],
  [/паллад|(?<![а-яёa-z])pd(?![а-яёa-z])/i, /паллад|palladium/i],
];
// Вес монеты из описания: «Au 3,14», «Ag 31,1», «серебро 15,55 г», «вес 11.3 гр».
const MASS = /(?:au|ag|pt|pd|золото|серебро|платина|вес)[^0-9]{0,8}(\d+(?:[.,]\d+)?)|(\d+(?:[.,]\d+)?)\s*(?:г|гр|грамм)(?![а-яё])/i;
const lotMass = (t) => {
  const m = String(t || "").match(MASS);
  const v = m ? parseFloat(String(m[1] || m[2]).replace(",", ".")) : NaN;
  return v > 0.3 && v < 2000 ? v : null;          // вне этих границ это проба, номер или тираж
};
const lotMetal = (t) => { for (const [re, m] of LOT_METAL) if (re.test(String(t || ""))) return m; return null; };
const enUnit = (u) => { for (const [re, en] of EN_UNIT) if (re.test(String(u || ""))) return en; return null; };

// Номинал в каталоге записан не только цифрой. Встречаются словесные числа («FIVE DOLLARS»),
// именованные монеты США («QUARTER», «DIME», «NICKEL») и запись со знаком доллара («$25»,
// «PLATINUM $10»). Собираем все допустимые написания для конкретного номинала лота.
const NUM_WORD = {
  1: "ONE", 2: "TWO", 3: "THREE", 4: "FOUR", 5: "FIVE", 6: "SIX", 7: "SEVEN", 8: "EIGHT",
  9: "NINE", 10: "TEN", 12: "TWELVE", 15: "FIFTEEN", 20: "TWENTY", 25: "TWENTY[- ]FIVE",
  50: "FIFTY", 100: "(ONE +)?HUNDRED", 0.5: "HALF", 0.25: "QUARTER",
};
// Народные имена монет США и Канады: «25 центов» в каталоге записаны как QUARTER, и наоборот.
const NAMED = [
  { unit: /^цент/, num: 25, re: "^QUARTER" }, { unit: /^доллар/, num: 0.25, re: "^QUARTER" },
  { unit: /^цент/, num: 10, re: "^DIME" }, { unit: /^цент/, num: 5, re: "^(HALF +DIME|NICKEL)" },
  { unit: /^цент/, num: 50, re: "^HALF +DOLLAR" }, { unit: /^доллар/, num: 0.5, re: "^HALF +DOLLAR" },
  { unit: /^цент/, num: 1, re: "^(ONE +)?(CENT|PENNY)" },
];
const sqlLit = (x) => "'" + String(x).replace(/'/g, "''") + "'";

function denomAlternatives(d) {
  const alts = ["denomination_text ~* $3"];                       // цифрой в начале — основной случай
  const numRe = d.fraction && d.raw ? d.raw.replace("/", " *[/] *") : String(d.num).replace(".", "\\.");
  alts.push(`denomination_text ~* ${sqlLit("[$]" + numRe + "([^0-9]|$)")}`);   // «$25», «PLATINUM $10»
  const en = enUnit(d.unit);
  const word = NUM_WORD[d.num];
  if (word && en) alts.push(`denomination_text ~* ${sqlLit("^" + word + "[ -]+" + en)}`);  // «FIVE DOLLARS»
  if (d.num === 1 && en) alts.push(`denomination_text ~* ${sqlLit("^(ONE +)?" + en + "S?( |$)")}`);
  for (const n of NAMED) if (n.num === d.num && n.unit.test(String(d.unit || ""))) alts.push(`denomination_text ~* ${sqlLit(n.re)}`);
  return alts;
}

// Русские имена стран, собранные ИЗ САМОГО КАТАЛОГА (таблица numis_country_ru): словарь
// numis_country_map знал 228 стран из 699, и «Великобритания» (1622 типа), «Китай» (1273),
// «Бавария» матчеру были неизвестны. Здесь имя сразу указывает на каталожное написание.
// Склонения режем по основе: «Германия»/«Германии» → «Германи».
// Название страны ищем СЛОВОМ, а не подстрокой. Поиск через includes давал тихую катастрофу:
// «эмали» содержит «мали», «лейб-гренадерского» — «гренад», и знаки с медалями уезжали в Мали и
// Гренаду (1838 и 230 лотов соответственно). Допускаем окончание не длиннее трёх букв — столько
// бывает при склонении («Германии», «Пруссию», «Финляндией»), но не «гренадерского».
const reEsc = (x) => String(x).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const wordRe = (stem) => new RegExp("(?<![а-яёa-z])" + reEsc(stem) + "[а-яё]{0,3}(?![а-яёa-z])", "i");

const ruStem = (s) => {
  const t = String(s || "").toLowerCase().trim();
  const cut = t.replace(/[аяиыоеёуюйьъ]$/i, "");
  return cut.length >= 5 ? cut : t;
};
let CRU = null;
async function catalogRu(pool) {
  if (!CRU) {
    const rows = (await pool.query("SELECT country, ru FROM numis_country_ru WHERE ru IS NOT NULL")).rows;
    const list = [];
    for (const r of rows) {
      const vars = Array.isArray(r.ru) ? r.ru : [];
      for (const v of vars) {
        const stem = ruStem(v);
        if (stem.length >= 4) list.push({ stem, country: r.country, re: wordRe(stem) });
      }
    }
    CRU = list.sort((a, b) => b.stem.length - a.stem.length);
  }
  return CRU;
}

// Одна страна живёт в каталоге под разными написаниями: «Kingdom Of Thailand» против «Thailand»,
// «Straits Settlement» против «Straits Settlements», «Congo, Democratic Republic» против
// «Democratic Republic of the Congo». Точный ключ их не сводит, и лот уходил в страну, которой в
// каталоге нет вовсе (одного Таиланда так потерялось 994 лота). Запасной ключ — НАБОР слов имени
// без окончаний множественного числа; названия считаем одной страной, когда набор одного целиком
// входит в набор другого. Подмножество, а не пересечение: у «United Kingdom» и «United States»
// общее слово есть, но ни одно не входит в другое целиком — они не сольются.
const CWORDS = (s) => new Set(String(s || "").toLowerCase().replace(/[^a-z0-9 ]/g, " ").split(/\s+/)
  .filter((w) => w && !/^(of|the|and)$/.test(w)).map((w) => w.replace(/s$/, ""))
  // хвост от апострофа: «People's» распадается на «people» и «s», и одинокая буква мешала
  // сойтись «China, People's Republic» с «China, Peoples Republic»
  .filter((w) => w.length > 1));
// Разница между написаниями допустима только в словах об устройстве государства («Kingdom of
// Thailand» и «Thailand» — одна страна). Слова «republic», «democratic», «peoples», «federal»
// сюда НЕ входят: ими различаются РАЗНЫЕ государства — Тайвань и КНР, ФРГ и ГДР, — и склеивать
// их нельзя.
const CEXTRA = /^(kingdom|state|sultanate|principality|emirate|duchy|grand|dominion|colony|territory|island)$/;
const sameCountry = (a, b) => {
  const [big, small] = a.size >= b.size ? [a, b] : [b, a];
  return [...small].every((w) => big.has(w)) && [...big].filter((w) => !small.has(w)).every((w) => CEXTRA.test(w));
};

let CMAP = null, CATC = null;
async function catalogCountry(pool, en) {
  if (!CATC) {
    CATC = new Map();
    const rows = (await pool.query("SELECT country, count(*)::int c FROM coin_type WHERE era='foreign' AND country IS NOT NULL GROUP BY 1")).rows;
    for (const r of rows) {                       // на коллизии ключа берём написание с бОльшим числом типов
      const k = normCountry(r.country);
      const cur = CATC.get(k);
      if (!cur || cur.c < r.c) CATC.set(k, r);
    }
  }
  const k = normCountry(en);
  const hit = CATC.get(COUNTRY_ALIAS[k] || k) || CATC.get(k);
  if (hit) return hit.country;
  // Точного ключа нет — пробуем сойтись по набору слов и берём написание с бОльшим числом типов.
  const want = CWORDS(en);
  if (want.size) {
    let best = null;
    for (const r of CATC.values()) {
      const have = CWORDS(r.country);
      if (!have.size || !sameCountry(want, have)) continue;
      if (!best || best.c < r.c) best = r;
    }
    if (best) return best.country;
  }
  return tc(en);                                 // такой страны в каталоге нет вовсе (совпадений не будет)
}
// Из нескольких совпавших стран выбираем ту, у которой в каталоге меньше типов: земля всегда
// меньше государства, а значит точнее. Счёт типов уже собран в CATC при первом обращении.
async function narrowest(pool, names) {
  let best = null, bc = Infinity;
  for (const n of names) {
    const r = (await pool.query(
      "SELECT count(*)::int c FROM coin_type WHERE era='foreign' AND country=$1", [n])).rows[0];
    if (r.c && r.c < bc) { bc = r.c; best = n; }
  }
  return best || names[0];
}

async function countryEn(pool, title) {
  if (!CMAP) {
    const rows = (await pool.query("SELECT ru,en FROM numis_country_map WHERE en IS NOT NULL")).rows
      .map((r) => ({ ru: r.ru, en: RU_OVERRIDE[r.ru] || r.en }))
      .concat(RU_EXTRA.map(([ru, en]) => ({ ru, en })));
    CMAP = rows.sort((a, b) => b.ru.length - a.ru.length).map((r) => ({ ...r, ruLc: r.ru.toLowerCase(), re: wordRe(r.ru.toLowerCase()) }));
  }
  const t = String(title || "").toLowerCase();    // заголовки на маркетплейсе часто КАПСОМ — сравниваем без регистра
  // В заголовке называют и государство, и его землю: «20 марок. Германия. Пруссия 1900». Тип в
  // каталоге лежит под землёй (Prussia), а не под государством, поэтому из всех совпавших имён
  // берём САМОЕ УЗКОЕ — то, у которого в каталоге меньше типов. Одиночное совпадение проходит
  // прежним путём и ничего не стоит.
  const hits = [];
  for (const r of CMAP) if (r.re.test(t)) hits.push(await catalogCountry(pool, r.en));
  if (hits.length) return hits.length === 1 ? hits[0] : await narrowest(pool, hits);
  // Курируемый словарь молчит — пробуем имена, собранные из каталога (они уже в его написании).
  for (const r of await catalogRu(pool)) if (r.re.test(t)) return await catalogCountry(pool, r.country);
  return null;
}

async function matchType(pool, p) {
  if (p.isSet || p.isNonCoin || !p.denom || !p.year) return null;
  const d = p.denom;
  // Рубль и копейку чеканила не только Россия: у Беларуси и Приднестровья свой рубль и своя
  // копейка, у Украины копейка, у Таджикистана и Латвии рубль ходил в девяностых. Если такая
  // страна названа в заголовке, в русские типы не идём — «1 рубль 2009 Беларусь» садился на нашу
  // ходячку. Список именно точечный: запрет «названа любая страна» отрезал бы «100 рублей. Победа
  // над Японией», где страна лишь часть сюжета.
  const RUB_STATES = /^(Belarus|Transnistria|Ukraine|Tajikistan|Latvia|Lithuania|Moldova)$/i;
  if (d.isRf) {
    if (d.value == null) return null;
    const own = String((await countryEn(pool, p.title)) || "");
    if (RUB_STATES.test(own)) return await matchForeignByCountry(pool, p, own);
    if (p.year < 1917) {                                  // ИМПЕРСКОЕ: двор-дизамбиг
      // Номер по Биткину бьёт все прочие признаки: он и есть точное указание на разновидность.
      // Номер не уникален в каталоге (у 472 номеров по два типа, у 168 по три) — это дубли одной
      // монеты из разных источников, ничью решаем как обычно, числом уже привязанных лотов.
      if (p.bitkin) {
        const byNum = (await pool.query(
          `SELECT id, name_full, mint,
                  (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links
             FROM coin_type WHERE era='imperial' AND bitkin_number=$1 AND ($2::int IS NULL OR year=$2)`,
          [p.bitkin, p.year])).rows;
        if (byNum.length) return { id: topOf(byNum).id, conf: 0.95, era: "imperial" };
      }
      const all = (await pool.query("SELECT id, name_full, metal, theme_ru, mint, (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links FROM coin_type WHERE era='imperial' AND ROUND(denomination_value,6)=ROUND(CAST($1 AS numeric),6) AND year=$2", [String(d.value), p.year])).rows;
      let rows = filterMetal(all, p.precious);
      if (rows.length === 1) return { id: rows[0].id, conf: 0.7, era: "imperial" };
      const marks = titleMarks(p.title);
      if (rows.length > 1 && marks) {
        const scored = rows.map((r) => [r, markScore(r.mint, marks)]).filter(([, sc]) => sc >= 0);
        const top = Math.max(0, ...scored.map(([, sc]) => sc));
        const f = scored.filter(([, sc]) => sc === top).map(([r]) => r);
        if (top > 0 && f.length === 1) return { id: f[0].id, conf: 0.85, era: "imperial" };
        if (f.length) rows = f;
      }
      const r = pickWithMetal(rows.length ? rows : all, p, 0.65, 0.8, true); return r ? { ...r, era: "imperial" } : null;
    }
    if (p.year <= 1991) {                                 // СССР: погодовка/памятные
      let rows = (await pool.query("SELECT id, name_full, metal, theme_ru, (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links FROM coin_type WHERE era='ussr' AND denomination_value=$1 AND year=$2", [d.value, p.year])).rows;
      // relax тот же, что в имперской ветке: серебро СССР (полтинник, рубль 1924, биллон 500-й)
      // это норма номинала, а не дорогой тёзка, и в заголовке металл называют не всегда.
      const r = pickWithMetal(rows, p, 0.65, 0.8, true); return r ? { ...r, era: "ussr" } : null;
    }
    let rows = (await pool.query("SELECT id, name_full, metal, theme_ru, mint, (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links FROM coin_type WHERE era IS NULL AND country='RU' AND denomination_value=$1 AND year=$2", [d.value, p.year])).rows;
    // Сначала тема, и только потом двор. Обратный порядок уже дал промах: у «25 рублей Сочи
    // Факел 2014 СПМД» отбор по двору оставил единственным кандидатом памятную монету Галилею,
    // и она была выбрана как безальтернативная. Двор решает лишь среди ТИРАЖНЫХ типов, где
    // различать больше нечем.
    let r = pickWithMetal(rows, p);
    if (!r) {
      const plain = rows.filter(isPlain);
      let byMint = p.modMints.length
        ? plain.filter((x) => p.modMints.includes(MOD_CANON[String(x.mint || "").trim()] || x.mint))
        : [];
      // Двор не назван — или назван, но отдельного типа под него нет (в спайн он не попал по
      // редкости): общий тиражный тип без двора подходит и в том, и в другом случае.
      if (!byMint.length) byMint = plain.filter((x) => !x.mint);
      if (byMint.length) r = { id: topOf(byMint).id, conf: 0.65 };
    }
    return r ? { ...r, era: "modern" } : null;
  }
  // ТЕРРИТОРИИ ИМПЕРИИ. Финляндия (пенни, марка, с 1864) и Царство Польское (грош, злотый,
  // с 1815) чеканили собственный номинал, но по коллекционерской традиции это русские монеты —
  // и в каталоге они лежат в имперской эре. Ищем их там по ТЕКСТУ номинала: рублёвого значения
  // у таких типов нет намеренно (1 пенни формально равен полушке и склеился бы с русским типом).
  // Германскую марку сюда пускать нельзя, поэтому требуем, чтобы страна лота не была распознана
  // как чужая: подходит только Финляндия, Польша, Россия или отсутствие страны в заголовке.
  const TERR_UNIT = /^(пенни|марк|грош|злот)/;
  const FOR_TERR = /для +(финлянд|польш|пруссии|царства +польского)/i;
  // Нижняя граница 1750, а не 1815: под Польшу её хватало, но прусские монеты русской чеканки
  // (занятая Пруссия при Елизавете) датируются 1759-1762 и в диапазон не попадали.
  if (p.year && p.year >= 1750 && p.year <= 1917 && TERR_UNIT.test(String(d.unit || ""))) {
    const cen = await countryEn(pool, p.title);
    // «Для Финляндии», «Для Пруссии», «Для Польши» — прямое указание, что монету чеканила Россия
    // для своей территории или занятой земли; по коллекционерской традиции это русские монеты.
    // Без этой оговорки распознанная чужая страна закрывала им путь в имперскую эру, и все 122
    // прусских лота висели сиротами при наличии типов («1 грош. Пруссия 1759»).
    if (!cen || /^(Finland|Poland|RU|Russia)$/.test(cen) || FOR_TERR.test(p.title)) {
      const numStr = String(d.num).replace(".", "\.");
      let rows = (await pool.query(
        `SELECT id, name_full, metal, theme_ru, denomination_text, issuer,
                (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links
           FROM coin_type
          WHERE era='imperial' AND year=$1 AND denomination_text ~* $2`,
        [p.year, "^" + numStr + " *" + String(d.unit).slice(0, 4)])).rows;
      // Территорию в названии типа пишут в именительном («1 грош. Пруссия»), а в заголовке лота
      // она склоняется («Для Пруссии»), и сравнение по целому слову не срабатывало. Сверяем по
      // основе — тем же способом, что и имена стран.
      const terr = (p.title.match(FOR_TERR) || [])[1];
      if (terr && rows.length > 1) {
        const st = ruStem(terr);
        const f = rows.filter((r) => ((r.name_full || "") + " " + (r.denomination_text || "") + " " + (r.issuer || ""))
          .toLowerCase().includes(st));
        if (f.length) rows = f;
      }
      const r = pickWithMetal(rows, p, 0.65, 0.8, true);
      if (r) return { ...r, era: "imperial" };
    }
  }
  // FOREIGN: страна+год+ведущее число (единица м.б. экзотическая/неизвестная). Граница номинала —
  // «^<num>(не-цифра|конец)», чтобы «10» не ловило «100». Единицу НЕ сверяем (даласи/бутут… не в словаре).
  const cen = await countryEn(pool, p.title); if (!cen) return null;
  return await matchForeignByCountry(pool, p, cen);
}

// Поиск среди иностранных типов по уже известной стране.
async function matchForeignByCountry(pool, p, cen) {
  const d = p.denom;
  // Краузе печатает единичный номинал ОДНИМ СЛОВОМ: «DOLLAR», «CROWN», «THALER», «PENNY» —
  // без цифры. Таких типов в каталоге 16 430, и требование ведущего числа делало их невидимыми.
  // Поэтому для номинала «1» принимаем и запись без цифры; для остальных — как было.
  // Дробные типы («1/2 DOLLAR») исключаем, если сам лот не дробный, иначе «1 доллар» садится на половину.
  // У дробного номинала ведущее число — сама дробь: «1/13», а не 0.0769.
  const lead = d.fraction && d.raw ? d.raw.replace("/", " *[/] *") : String(d.num).replace(".", "\\.");
  const denomRe = "^" + lead + "([^0-9]|$)";
  // ...но принимать ЛЮБУЮ бесцифровую запись нельзя: под «1» попадут разом DOLLAR, HALF DOLLAR и
  // TWENTY DOLLARS, кандидатов станет много и матчер воздержится. Поэтому сверяем ЕДИНИЦУ:
  // «1 доллар» ищет «DOLLAR»/«ONE DOLLAR», а не всё подряд.
  const denomCond = "(" + denomAlternatives(d).join(" OR ") + ")";
  const fracGuard = d.fraction ? "" : " AND denomination_text !~ '^[0-9]+ *[/] *[0-9]'";
  // Тип Краузе — это KM#, а не отдельный год: одна строка каталога покрывает весь период чеканки
  // (Пруссия KM#481 — 1861-1873), и в колонке year лежит только ПЕРВЫЙ год. Сверка по нему теряла
  // лоты всех остальных годов, а таких типов в спайне 10 тысяч. Ищем попадание года В ДИАПАЗОН,
  // а где диапазона нет — по-прежнему точное совпадение.
  let rows = (await pool.query(
    `SELECT id, name_full, metal, theme_ru, mass, denomination_text,
              (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links
       FROM coin_type WHERE era='foreign' AND country=$1
       AND $2 BETWEEN COALESCE(year_start, year) AND COALESCE(year_end, year)
       AND ${denomCond}${fracGuard}`, [cen, p.year, denomRe])).rows;
  // Единицу номинала СВЕРЯЕМ, когда знаем её английское имя. Раньше сверялось только ведущее
  // число, и «10 фунтов» получал в кандидаты «10 PENCE», «5 долларов» — «5 CENTS», а
  // «1/2 соверена» — «1/2 PENNY». Кандидатов набиралось по десятку, различить их было нечем, и
  // матчер воздерживался. Экзотические единицы (даласи, бутут) в словаре не значатся — там
  // по-прежнему решает число.
  const en = enUnit(d.unit);
  if (en && rows.length > 1) {
    // Единицу пишут и по-английски («2 MARK»), и по-русски — у типов, собранных из описаний
    // аукциона, она русская («2 марки»). Принимаем оба написания, иначе фильтр выбрасывает
    // ровно тот тип, на котором лот и должен был сойтись.
    const re = new RegExp("(?<![A-Z])" + en + "S?(?![A-Z])", "i");
    const ru = new RegExp("(?<![а-яё])" + String(d.unit).slice(0, 4) + "[а-яё]*(?![а-яё])", "i");
    const f = rows.filter((x) => {
      const txt = String(x.denomination_text || "") + " " + String(x.name_full || "");
      return re.test(txt) || ru.test(txt);
    });
    if (f.length) rows = f;
  }
  // Названный в лоте драгоценный металл — не только защита от дешёвого тёзки, но и признак
  // выбора: у «5 долларов. Ниуэ 2009г. Au» среди кандидатов и серебро, и золото.
  const want = lotMetal(p.title);
  if (want && rows.length > 1) {
    const f = rows.filter((x) => want.test(String(x.metal || "")));
    if (f.length) rows = f;
  }
  // Вес из описания («Au 3,14», «серебро 31,1 гр») различает то, что не различает ничто другое:
  // у «15 долларов. Австралия 2005» четыре золотых кандидата одного номинала и года, и отличаются
  // они именно весом. Допуск 3% — на разнобой в округлении справочников.
  // ⚠️ Сейчас признак БЕЗДЕЙСТВУЕТ: coin_type.mass у иностранных типов пуст у всех 90 тысяч, а в
  // текстовом слое разобранных томов Краузе веса нет вовсе (проверено по coin_ref_raw). Условие
  // оставлено, чтобы заработать сразу, как только вес появится, — но пока это не признак.
  const gr = lotMass(p.title);
  if (gr && rows.length > 1) {
    const f = rows.filter((x) => x.mass != null && Math.abs(+x.mass - gr) / gr < 0.03);
    if (f.length) rows = f;
  }
  const r = pickWithMetal(rows, p); return r ? { ...r, era: "foreign" } : null;
}

