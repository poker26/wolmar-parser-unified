/**
 * Общий матчер «лот → coin_type» для всех источников (meshok/auction.ru/wolmar) и ВСЕХ эр.
 * parseTitle(title) → атрибуты; matchType(pool, parsed) → {id, conf, era} | null (abstain).
 * Эра-роутинг по номиналу+году: имперское<1917 / СССР 1921-1991 / модерн-РФ≥1992 / foreign(нерублёвое|страна).
 * Тема/двор-дизамбигуация при мульти-кандидате; abstention если не различить (не угадываем — чтобы не засорять).
 */
const tc = (s) => s.toLowerCase().replace(/(^|\s)\S/g, (c) => c.toUpperCase());
// «коллекци» УБРАН: ловил зазывалку «в коллекцию!» на одиночках. Реальные коллекции ловят набор/подборка/N монет.
// «Лот» само по себе НЕ набор: так продавцы помечают номер лота («(Лот Ф576)»). Набором его
// делает только счёт — «лот из 3 монет» или «сборный лот». «Перепутка» тоже убрана: это
// разновидность штемпеля ОДНОЙ монеты, а не подборка.
// Счёт штук и монет — признак набора, но НЕ когда рядом слово «тираж»: «ТИРАЖ - 50 000 шт»
// говорит о тираже типа, а продаётся одна монета.
const SET = /набор|комплект|подборк|(?<![а-яё])лот[а-яё]*\s+из\s+(?:\d|двух|тр[её]х|четыр[её]х|пяти|шести|семи|восьми|девяти|десяти)|сборн[а-яё]+\s+лот|(?<!тираж[^|]{0,20})(?:\d+\s*(?:монет|шт|экземпляр))|погодовк|альбом/i;
// НЕ монета: банкноты/боны/жетоны/медали/марки/прочее — отсекаем (маркетплейс мешает всё)
// ВАЖНО: голые «серия»/«номер» НЕ-банкнотный признак (монеты тоже в сериях) → убраны.
// Банкнота-серийник = две заглавные буквы + 6+ цифр (АА 1234567). PMG/PPQ — грейдинг БУМАГИ.
// +бумажные деньги/боны: казначейский/банковый/кредитный билет, ассигнация, «Образец» нот.
const HARD_NONCOIN = /банкнот|купюр|(?<![а-яё])бон[аы](?![а-яё])|(?<![а-яё])боны(?![а-яё])|\bpmg\b|\bppq\b|пачка|облигаци|казначейск|ассигнаци|кредитный\s+билет|банковый\s+билет|билет\s+государственн|сер(?:ия|\.)?\s*[А-ЯЁ]{2}\s*№?\s*\d{6,}|(?<![а-яё])бумага(?![а-яё])|(?<![а-яё])бумажн|(?:расч[её]тн|товарн|денежн)[а-яё]+ +ордер|потребительск|кооператив|товариществ[оа]|шорно|губернск[а-яё]+ +союз|обществ[оа] +потребител|арктикугол|рябченко|кардаков|обязательств|квитанци|отделени[ея] +государственного +банка|биржев[а-яё]+ +комитет|коммерческ[а-яё]+ +банк|казначейств[оа]|разменн[а-яё]+ +знак|краткосрочн|копилк|сувенир|брелок|(?<![а-яё])магнит(?![а-яё])|расч[её]тн[а-яё]+ +знак|водян[а-яё]+ +знак|денежн[а-яё]+ +знак|платежн[а-яё]+ +обязательств|спасская башня|ярославль 1000/i;
// «Мягкие» признаки: эти вещи ходят В ПАРЕ с монетой («с сертификатом», «с 1 жетоном», «в
// футляре»), и раньше такой лот целиком объявлялся не-монетой. Заголовок называет главный
// предмет первым, поэтому мягкий признак учитываем только в его начале. «Марка» отдельно: с
// числом впереди это НОМИНАЛ («2 марки 1934. Германия»), а не почтовая марка.
const SOFT_NONCOIN = /жетон|медал[ьи]|значок|открытк|конверт|купон|лотере|акци[яи](?![а-яё])|вексел|замещени|знак +(?:отличия|ордена|для)|нагрудн[а-яё]+ +знак|георгиевск[а-яё]+ +крест|фотограф|табакерк|ложк|вилк|портсигар|брошь|серьг|перстень|икон[аы]|оклад|подстаканник|запонк|медальон|погон[ыа]?|петлиц|эполет|пряжк|пуговиц|шпаг|сабл|кортик|(?<![а-яё])кольцо(?![а-яё])|браслет|цепочк|кулон|колье|шкатулк|самовар|подсвечник|статуэтк|(?<!\d\s?)(?<![а-яё])марк[аи](?![а-яё])/i;
// Предмет, названный ПЕРВЫМ СЛОВОМ заголовка, и есть предмет лота. Позиционного признака «в первых
// 42 символах» тут мало: «10 копеек 1916 г. Без знака минцмейстера» — монета, а «Знак Авангард
// III место» — значок, и отличаются они только тем, стоит ли слово в начале. Одних значков в
// монетной таблице оказалось 24 761.
const LEAD_NONCOIN = /^[«"'(\[\s]*(знак|плакет|орден(?![а-яё]*ск)|крест(?![а-яё]*овик)|сахарниц|ваз[аы]|должностн|подстаканник|портсигар|брошь|кольцо|браслет|цепочк|медальон|жетон|значок|погон|эполет|аксельбант|печат[ьи]|пряжк|пуговиц|шкатулк|самовар|подсвечник|статуэтк|фотограф|табакерк|ложк|вилк|нож(?![а-яё])|каталог|книг|альбом|открытк|конверт|марк[аи](?![а-яё])|медал[ьи]|бона|боны|банкнот|купюр|облигаци|сертификат|акци[яи]|вексел|билет|талон|ордер|карточк|удостоверени|диплом|грамот|лент[аы]|колодк)/i;

// Античность и раннее средневековье — вне текущего охвата: справочники на них у нас другие
// (Sear, RIC, SNG, Album), и типов в каталоге нет ни одного. Это МОНЕТЫ, поэтому в «не наш
// предмет» они не идут — им отдельный вид в разметке. Узнаём по названию номинала и по имени
// государства: «динар» и «дирхам» сами по себе не признак — они и сегодня в ходу.
const ANCIENT = /(?<![а-яё])(тетрадрахм|дидрахм|драхм|обол|статер|денари[йя]|антониниан|фоллис|сестерци|дупонди|тетрахалк|халк[оа]?|ауреус|солид|силикв|милиарис|нумми|литра|тритартеморий)[а-яё]*(?![а-яё])|(?<![а-яё])(древн[а-яё]+ +(рим|греци)|византи|боспор|ольви|пантикапе|херсонес|селевкид|птолеме|парфи|сасанид|кушан|аббасид|омейяд|саманид|бактри|эллинист|антич)[а-яё]*/i;

const isNonCoin = (t) => HARD_NONCOIN.test(t) || LEAD_NONCOIN.test(String(t || "").trimStart()) || SOFT_NONCOIN.test(String(t || "").slice(0, 42));
const MINT = /(?<![А-Яа-яЁё])(СПБ|СПМ|СПМД|ММД|ЛМД|ЕМ|ВМ|КМ|ТМ|АМ|ИМ|БМ|СМ|ММ|МД)(?![А-Яа-яЁё])/g;
// Драг-сигнал в ОПИСАНИИ лота (продавец почти всегда называет металл/пруф — это цена монеты).
const PRECIOUS_SIG = /золот|сереб|платин|паллад|\bпруф\b|\bproof\b|инвестиц|унци|\bau\b|\bag\b|\bpt\b|\bpd\b/i;
// Драг-металл в ТИПЕ каталога (coin_type.metal = «золото 999/1000» / «серебро 925/1000» …).
const PRECIOUS_METAL = /золот|сереб|платин|паллад/i;
// Дизамбиг по металлу: нет драг-сигнала в описании → выкидываем драгоценных кандидатов (дешёвый тёзка ≠ золотой тип).
// Если все кандидаты драгоценные → вернётся пусто → abstain (лучше не сматчить, чем сесть на золото за ×400).
const filterMetal = (rows, precious) => precious ? rows : rows.filter((r) => !PRECIOUS_METAL.test(r.metal || ""));

// Зазывалка стартовой ставки: «С 1 рубля», «Аукцион с 1 рубля», «от 1 руб.». Это НЕ номинал, но
// именно он попадался разбору первым и делал «Замбия 1 квача 2017 года. С 1 рубля» рублёвым лотом
// 1992+ — так в модерн-РФ утекали тысячи иностранных монет. Латинская «c» тоже встречается.
const BID_JARGON = /(?<![а-яёa-z])(?:[сc]|от)\s*\d*\s*руб(?:л[а-яё]*)?\.?(?![а-яёa-z])/gi;
// Оценка по справочнику («Петров - 1,25 рубля», «Ильин - 5 рублей») — тоже не номинал лота.
// Из-за неё «Полуполтинник 1770г. ММД ДМ. Ag. Петров - 1,25 рубля» уходил в рублёвые типы.
const REF_PRICE = /(петров|ильин|уздеников|конрос|биткин)[^|.;]{0,15}?\d+(?:[.,]\d+)?\s*руб[а-яё]*/gi;

// Словесные номиналы: до XX века их писали именно так, и это ЕДИНСТВЕННОЕ указание на номинал в
// заголовке — «Полуполтинник 1770г. ММД ДМ» цифры не содержит вовсе. Таких сирот 17,5 тысяч.
// Червонец сюда не берём намеренно: у него нет постоянного рублёвого значения.
const NAMED_RU = [
  [/(?<![а-яё])полушк[аи]?(?![а-яё])/i, 0.0025, "полушка"],
  [/(?<![а-яё])ден[ьг]?г[аи]?(?![а-яё])/i, 0.005, "денга"],
  [/(?<![а-яё])полуполтинник[а]?(?![а-яё])/i, 0.25, "полуполтинник"],
  [/(?<![а-яё])полтин(?:а|ы|ник[а]?)(?![а-яё])/i, 0.5, "полтина"],
  [/(?<![а-яё])гривенник[а]?(?![а-яё])/i, 0.1, "гривенник"],
  [/(?<![а-яё])пятиалтынн[ыо][йг][оа]?(?![а-яё])/i, 0.15, "пятиалтынный"],
  [/(?<![а-яё])двугривенн[ыо][йг][оа]?(?![а-яё])/i, 0.2, "двугривенный"],
  [/(?<![а-яё])алтын[а]?(?![а-яё])/i, 0.03, "алтын"],
  [/(?<![а-яё])пятак[аи]?(?![а-яё])/i, 0.05, "пятак"],
  // Полкопейки — та же денга: рублёвое значение у них общее, и типы в каталоге лежат под «денгой».
  [/(?<![а-яё])пол[- ]?копейк[аи]?(?![а-яё])/i, 0.005, "полкопейки"],
];
// Червонец рублёвого значения не имеет вовсе — ни у Петра, ни у советского 1975-1982. Такие
// номиналы ищем ТЕКСТОМ: в каталоге они и записаны словом. Лотов только с червонцем 2007.
const NAMED_TEXT = [[/(?<![а-яё])червон(?:ец|ца|цев)(?![а-яё])/i, "червонец"]];

const parseDenom = (t) => {
  const s = String(t || "").replace(REF_PRICE, " ").replace(BID_JARGON, " ").replace(/½/g, "0.5 ").replace(/¼/g, "0.25 ").replace(/¾/g, "0.75 ");
  // Словесный номинал проверяем первым: если он назван, цифры в заголовке — это год, тираж или
  // ссылка на справочник, а не номинал.
  for (const [re, value, unit] of NAMED_RU) if (re.test(s)) return { num: value, unit, value, isRf: true, named: true };
  for (const [re, unit] of NAMED_TEXT) if (re.test(s)) return { num: null, unit, value: null, isRf: true, named: true, textOnly: true };
  // Смешанная дробь: «2 1/2 доллара» (квотер-игл), «1 1/2 рубля». Разбирать её надо ПЕРВОЙ, иначе
  // дробная часть отрывается от целой и монета в два с половиной доллара становится полудолларом.
  const mix = s.match(/(\d+)\s+(\d+)\s*[/]\s*(\d+)\s*([а-яё]{3,})/i);
  if (mix && +mix[3] !== 0) {
    const unit = mix[4].toLowerCase();
    if (!/^(год|лет|грамм|сохран|экземпл|штук|монет|тысяч|миллион|часть|разн)/.test(unit)) {
      const num = +mix[1] + +mix[2] / +mix[3];
      return { num, unit, value: /^копе/.test(unit) ? num / 100 : num, isRf: /^(рубл|копе)/.test(unit),
               fraction: true, raw: mix[1] + " " + mix[2] + "/" + mix[3] };
    }
  }
  // Дробные номиналы («1/2 копейки», «3/4 рубля», «1/2 доллара») разбираем ДО обычного: обычная
  // регулярка ищет «число + единица» в любом месте строки и выхватывает из дроби знаменатель —
  // «1/2 копейки» становилось «2 копейки», то есть номиналом вчетверо крупнее. Раньше этот блок
  // стоял ниже и не срабатывал никогда.
  const fr = s.match(/(\d+)\s*\/\s*(\d+)\s*([а-яё]{3,})/i);
  if (fr && +fr[2] !== 0) {
    const unit = fr[3].toLowerCase();
    if (!/^(год|лет|грамм|сохран|экземпл|штук|монет|тысяч|миллион|часть|разн)/.test(unit)) {
      const num = +fr[1] / +fr[2];
      // Запись дроби храним как есть: иностранные типы Краузе печатают номинал именно так
      // («1/13 SHILLING», «2/3 THALER»), и искать их десятичной дробью бесполезно.
      return { num, unit, value: /^копе/.test(unit) ? num / 100 : num, isRf: /^(рубл|копе)/.test(unit),
               fraction: true, raw: fr[1] + "/" + fr[2] };
    }
  }
  const m = s.match(/(\d+(?:[.,]\d+)?)\s*(рубл[а-яё]*|копе[а-яё]*|евро|доллар[а-яё]*|центов?|пенс[а-яё]*|пенни|фунт[а-яё]*|тенге|гривен|гривн[а-яё]*|сум[а-яё]*|песо|юан[а-яё]*|лир[а-яё]*|динар[а-яё]*|дирхам[а-яё]*|драм[а-яё]*|манат[а-яё]*|франк[а-яё]*|сантим[а-яё]*|раппен[а-яё]*|крон[а-яё]*|эре|эйре|вон[а-яё]*|иен[а-яё]*|йен[а-яё]*|рупи[а-яё]*|реал[а-яё]*|шиллинг[а-яё]*|форинт[а-яё]*|злот[а-яё]*|грош[а-яё]*|стотинк[а-яё]*|бат[а-яё]*|лев[а-яё]*|пфенниг[а-яё]*|марок|марк[аи]|пиастр[а-яё]*|филс|эскудо|афгани)/i);
  if (m) {
    const unit = m[2].toLowerCase();
    // Число берём ОДИН раз с заменой запятой: раньше value считался из сырой строки, и
    // parseFloat("1,25") обрывался на запятой — номинал 1,25 молча превращался в 1.
    const num = parseFloat(m[1].replace(",", "."));
    return { num, unit, value: /^копе/.test(unit) ? num / 100 : num, isRf: /^(рубл|копе)/.test(unit) };
  }
  // fallback для ИНОСТРАННЫХ экзотических единиц (даласи/бутут/нгултрум/квача…): «<число> <слово>»,
  // исключая не-номинальные слова (год/вес/набор). value=null (неизвестна рублёвая привязка), isRf=false.
  const g = s.match(/(?:^|[^\wа-яё])(\d+(?:[.,]\d+)?)\s+([а-яё]{3,})/i);
  if (g) {
    const unit = g[2].toLowerCase();
    // Степень ордена, проба металла, калибр и размер числом с существительным выглядят как
    // номинал экзотической валюты — через них знаки отличия и ювелирка попадали в монеты.
    if (/^(год|лет|грамм|сохран|экземпл|штук|монет|рубл|копе|тысяч|миллион|часть|разн|степен|проб|калибр|размер|номер|класс|разряд|балл|верст|аршин|золотник|январ|феврал|март|апрел|мая|май|июн|июл|август|сентябр|октябр|ноябр|декабр|предмет|персон|экз|стран|листов|томов)/.test(unit)) return null;
    return { num: parseFloat(g[1].replace(",", ".")), unit, value: null, isRf: false, generic: true };
  }
  return null;
};
const STOP = new Set(["года", "год", "монета", "штук", "редкая", "оригинал", "слаб", "топ", "грейд", "аукцион", "рубля", "копеек", "редкость", "состояние"]);
// Название денежной единицы темой не является, а раньше ею считалось — и это ломало сам принцип
// дизамбигуации: слово «рубль» есть в имени КАЖДОГО кандидата, поэтому совпадение находилось у
// всех сразу, и «1 рубль 1992 ММД» садился на первый попавшийся памятный тип с уверенностью 0.8.
const UNIT_WORD = /^(рубл|копе|доллар|цент|евро|франк|фунт|крон|песо|динар|дирхам|шиллинг|злот|гривн|тенге|юан|иен|йен|рупи|лир[аы]|драм|манат|форинт|эскудо|пенни|пенс|марок|пиастр|стотинк|сантим|раппен|афгани|монет|росси)/;
const themeWords = (t) => [...new Set(String(t || "").toLowerCase().replace(/[^а-яёa-z0-9 ]/g, " ").split(/\s+/)
  .filter((w) => w.length >= 4 && !STOP.has(w) && !UNIT_WORD.test(w) && !/^\d+[а-яё]?$/.test(w)))];

// Дворы модерна пишут иначе, чем имперские: на рубле «ММД»/«СПМД», а на копейке одна буква
// «М»/«С-П». Разбираем отдельно от MINT — туда одиночную букву класть нельзя: имперская ветка
// сверяет двор ПОДСТРОКОЙ названия типа, и «М» совпала бы почти со всем.
const MOD_MINT = /(?<![А-Яа-яЁё])(СПМД|ММД|ЛМД|С-П|СП|М|Л)(?![А-Яа-яЁё])/g;
const MOD_CANON = { "М": "ММД", "ММД": "ММД", "Л": "ЛМД", "ЛМД": "ЛМД", "СП": "СПМД", "С-П": "СПМД", "СПМД": "СПМД" };
const modernMints = (t) => [...new Set([...String(t || "").matchAll(MOD_MINT)].map((m) => MOD_CANON[m[1]]).filter(Boolean))];

// Год чеканки — не обязательно первое четырёхзначное число в заголовке: у памятных монет впереди
// стоит историческая дата («3 рубля. Северный конвой. 1941-1945 гг. 1992г. ЛМД» — монета 1992-го,
// а разбор брал 1941). Приоритет: год с пометкой «г.»; затем год вне диапазона «1941-1945»; и
// только потом первое попавшееся число.
const YEAR = /(1[5-9]\d{2}|20[0-3]\d)/g;
function parseYear(t) {
  const s = String(t || "");
  const dated = s.match(/(1[5-9]\d{2}|20[0-3]\d)\s*(?:г\b|г\.|год)/i);
  if (dated) return +dated[1];
  const ranges = [...s.matchAll(/(1[5-9]\d{2}|20[0-3]\d)\s*[-–—]\s*(1[5-9]\d{2}|20[0-3]\d)/g)];
  const inRange = (y) => ranges.some((r) => y >= +r[1] && y <= +r[2]);
  const all = [...s.matchAll(YEAR)].map((m) => +m[1]);
  return all.find((y) => !inRange(y)) ?? all[0] ?? null;
}

// Номер по Биткину продавцы пишут прямо в описании («Биткин №# 944.203»), и это самый точный
// признак имперской монеты: он задаёт разновидность вместе с годом и двором. Слово «Биткин»
// без номера («Биткин редкость - R») — не идентификатор, его не берём.
const BITKIN = /биткин[^0-9|]{0,6}(\d+(?:\.\d+)*)/i;

function parseTitle(title) {
  const t = String(title || "");
  const denom = parseDenom(t);
  const year = parseYear(t);
  const mints = [...new Set([...t.matchAll(MINT)].map((m) => m[1]))];
  const grade = (t.match(/\b(MS\s?7\d|MS\s?6\d|PF\s?7\d|PF\s?6\d|Proof|пруф|UNC|АНЦ|aUNC|AU|XF|VF|VG)\b/i) || [])[1] || null;
  // Год решает: греческая драхма 1988 года — обычная современная монета, а не античность.
  // Признак действует только там, где года нет вовсе или он дописьменный для наших справочников.
  return { title: t, denom, year, isAncient: ANCIENT.test(t) && (!year || year < 1500), mints, modMints: modernMints(t), bitkin: (t.match(BITKIN) || [])[1] || null, grade, isSet: SET.test(t), isNonCoin: isNonCoin(t), precious: PRECIOUS_SIG.test(t), words: themeWords(t) };
}

// дизамбиг по словам темы: среди кандидатов выбрать с макс. совпадением; при мульти требовать overlap>0
// УЧАСТИЕ ТИПОВ В ОТБОРЕ (правило, а не случайность).
// В отборе участвуют ВСЕ типы независимо от `status` и `source`. Статус в этой базе означает
// происхождение, а не качество: `catalog` — навалом загруженный спайн Краузе, `confirmed` — и
// разобранные тома, и типы, собранные из описаний аукциона, `draft` — национальные справочники
// (испанский Calicó, шведский Myntboken). Исключать draft нельзя: это настоящие каталоги, на них
// уже 12 774 прохода. Порядок предпочтения при равенстве прочего:
//   1. точное совпадение по идентификатору — номер Биткина из описания лота (conf 0.95);
//   2. совпадение по теме/сюжету;
//   3. совпадение по двору и инициалам минцмейстера;
//   4. число уже привязанных лотов, затем меньший id — так дубли одной монеты из разных
//      источников не растаскивают проходы по двум карточкам.
// Источник на приоритет НЕ влияет: тип из аукционных описаний и тип из тома Краузе равны, пока
// одного из них не выделит признак выше.

// Сравнение темы идёт по ОСНОВЕ слова, а не по целому: тип называется «10 копеек. Сибирь», а в
// лоте «Сибирская монета» — целые слова не совпадают, и 229 сибирских монет висели сиротами при
// наличии типов. Основой считаем первые пять букв: этого хватает, чтобы «сибирская» сошлась с
// «Сибирь», и мало, чтобы склеить разные сюжеты — короткие и служебные слова сюда всё равно не
// доходят, их отсеивают STOP, UNIT_WORD и NON_THEME.
// Сравниваем ПО СЛОВАМ, а не подстрокой. Подстрока давала тихие промахи: «мира» из «Чемпионат
// мира по футболу» сидит внутри «Влади\\мира», и лот уезжал к «Творчеству Владимира Высоцкого».
// Основа в пять букв нужна для склонений («сибирская» → «Сибирь»), поэтому сверяем в обе стороны.
const wordsOf = (s) => String(s || "").toLowerCase().match(/[а-яёa-z0-9]{3,}/g) || [];
const themeHit = (nfWords, w) => nfWords.some((x) => x === w
  || (w.length >= 6 && x.startsWith(w.slice(0, 5)))
  || (x.length >= 6 && w.startsWith(x.slice(0, 5))));

// Сюжет типа, названный прямо в начале заголовка, — признак сильнее любого совпадения слов:
// продавец пишет предмет сразу после номинала («3 рубля. Рак 2004г. СПМД»). Отбрасывать по одному
// слову тут нельзя: описание памятной монеты ЦБ — это проза, и в ней найдётся и «Северном
// полушарии», и «знак зодиакального созвездия», из-за чего «Рак» уезжал то к «Северному оленю»,
// то к «Церкви Знамения».
const subjectOf = (row) => {
  const n = String(row.name_full || "").toLowerCase();
  const i = n.indexOf(". ");
  // Нет отделённой точкой части — у типа нет и сюжета, только номинал. Возвращать его нельзя:
  // «1 рубль» встречается в начале любого рублёвого заголовка, и тиражный тип выигрывал у всех.
  return i < 0 ? "" : n.slice(i + 2).split(/[,(]/)[0].trim();
};
function pickBySubject(rows, title) {
  const head = String(title || "").toLowerCase().slice(0, 70);
  const hit = rows.filter((r) => { const s = subjectOf(r); return s.length >= 3 && head.includes(s); });
  if (!hit.length) return null;
  // Несколько сюжетов подряд — берём самый длинный: он точнее («Северный олень» против «олень»).
  const best = hit.sort((a, b) => subjectOf(b).length - subjectOf(a).length)[0];
  return { id: best.id, conf: 0.9 };
}

// Ничью между одинаково подходящими типами решает число уже привязанных лотов: в каталоге есть
// дубли из разных источников («Полтина 1817 СПБ ПС» со 169 проходами и её же копия с одним), и
// произвольный выбор растаскивал проходы одной монеты по двум карточкам.
const better = (a, b) => (+b.links || 0) - (+a.links || 0) || a.id - b.id;
const topOf = (list) => list.slice().sort(better)[0];

function pickByTheme(rows, words, single = 0.65, themed = 0.8) {
  if (!rows.length) return null;
  if (rows.length === 1) return { id: rows[0].id, conf: single };
  let best = null, bs = 0, tied = [];
  // Слова о состоянии и отсылки к справочникам из отбора убираем: у типов, собранных из описаний
  // wolmar, они попали в САМО НАЗВАНИЕ («20 копеек. Чеканный блеск. Легкая патина»), и лот
  // выбирал разновидность по слову «блеск» вместо тиражного типа.
  const th = words.filter((w) => !NON_THEME.test(w));
  // Сравниваем и с русским сюжетом: у типов из томов Краузе имя собрано по-английски
  // («3 REICHSMARK. GERMANY - Waldeck»), и русские слова заголовка лота с ним не пересекались.
  for (const r of rows) {
    const nf = wordsOf((r.name_full || "") + " " + (r.theme_ru || ""));
    const sc = th.filter((w) => themeHit(nf, w)).length;
    if (sc > bs) { bs = sc; best = r; tied = [r]; }
    else if (sc === bs && bs > 0) tied.push(r);
  }
  if (!best || bs === 0) return null;                            // мульти без темы → abstain
  // Ничья по теме: одинаково подходят РАЗНЫЕ сюжеты — значит заголовок их не различает, и выбирать
  // нельзя. «25 рублей. Оружие великой Победы 2019» одинаково похоже на всю серию (Кошкин,
  // Дегтярёв, Шпагин), и число проходов тут не аргумент. Разрешаем ничью только между дублями —
  // типами с ОДНИМ и тем же названием.
  const uniq = new Set(tied.map((r) => String(r.name_full || "").toLowerCase().trim()));
  if (uniq.size > 1) return null;
  return { id: topOf(tied).id, conf: themed };
}

// Служебные слова заголовка: сохранность, металл, оформление, отсылки к справочникам. Годятся,
// чтобы отличить один памятный тип от другого, не годятся — они есть у всех подряд.
const NON_THEME = /^(исполнени|цветн|специальн|обычн|улучшенн|качеств|мельхиор|латун|стал[иья]|никел|биметалл|бронз|медно|серебр|золот|платин|паллад|проба|блеск|патина|сохран|состоян|отличн|прекрасн|слаб[еы]|оригинал|подлинн|тираж|монетн|двор[еа]?|биткин|уздеников|петров|ильин|конрос|редк|нечаст|немагнит|магнитн|гурт|штемпел|чекан|коллекц|аукцион|лоты|торг|спмд|ммд(?![а-яё])|лмд|петербургск|екатеринбургск|сузунск|аннинск|сестрорецк|колыванск|таврическ|варшавск|кадашевск|изображен|надпис|рельефн|справа|слева|сверху|снизу|вверху|внизу|центре|фоне|окружност|строк|обозначен|стилизован|надчекан|номинал|товарн)/;

// Знаки на имперской монете — это двор И инициалы минцмейстера («ММД ДМ», «СПБ ЭБ», «СМ АИ»).
// В MINT инициалы не входят, поэтому «Полуполтинник 1770 ММД ДМ» и «…ММД EI» были неразличимы и
// лот садился на любой из них. Собираем из заголовка ВСЕ заглавные аббревиатуры и требуем, чтобы
// знаки типа целиком нашлись среди них. У заголовка, набранного капсом целиком, признак не
// работает — там заглавное всё, поэтому такие пропускаем.
const MARK = /(?<![А-ЯЁA-Za-zа-яё])[А-ЯЁA-Z]{1,3}(?![А-Яа-яЁёA-Za-z])/g;
function titleMarks(t) {
  const words = String(t || "").split(/\s+/).filter((w) => /[А-Яа-яЁёA-Za-z]/.test(w));
  const caps = words.filter((w) => w === w.toUpperCase()).length;
  if (!words.length || caps / words.length > 0.6) return null;      // капс — признак бесполезен
  return [...new Set([...String(t).matchAll(MARK)].map((m) => m[0].toUpperCase()))];
}
// Все знаки типа найдены в заголовке → счёт равен их числу; хотя бы один не найден → тип не наш.
function markScore(typeMint, marks) {
  const tk = String(typeMint || "").toUpperCase().split(/\s+/).filter(Boolean);
  if (!tk.length) return 0;
  return tk.every((x) => marks.includes(x)) ? tk.length : -1;
}

// Простой тип — тот, у кого в названии только номинал: «20 копеек». Разновидности несут описание
// после точки («20 копеек 1975. Ости колосьев…»).
const isPlain = (row) => !/\.\s+\S/.test(String(row.name_full || ""));

// Выбор кандидата с гейтом по металлу и двумя запасными ходами.
// Гейт нужен: без драг-сигнала в описании дешёвый тёзка не должен садиться на золотой тип.
// Но памятные монеты почти все серебряные, а продавец металл сплошь и рядом не пишет — тогда
// гейт убирал ВСЕХ кандидатов, хотя тема совпадала однозначно («3 рубля 1994 Суриков» при
// единственном кандидате «3 рубля. В.И. Суриков»). И отдельно: если тема не различает вовсе,
// а среди кандидатов ровно один простой тип, лот без признаков разновидности логично отдать ему —
// иначе вся ходячка остаётся сиротами.
// Назван ли в заголовке САМ СЮЖЕТ — слова, которые могли бы указать на конкретную монету. Если
// назван, а ни один кандидат ему не отвечает, значит нужного типа у нас нет, и подставлять вместо
// него тиражный нельзя: именно так generic-тип «1 рубль 1990» собрал в одну ценовую корзину Чехова,
// Райниса и Чайковского, а «10 рублей 2015» — три разных сюжета Победы.
const namedSubject = (p) => p.words.some((w) => !NON_THEME.test(w));

function pickWithMetal(rows, p, single = 0.65, themed = 0.8, relax = false) {
  if (rows.length > 1) { const bySubj = pickBySubject(rows, p.title); if (bySubj) return bySubj; }
  // relax — для имперской эры: там серебро и золото это норма, а не дорогой тёзка дешёвого типа,
  // и продавец металл часто не пишет («Полтина 1817 СПБ ПС»). Если гейт убрал ВСЕХ кандидатов,
  // предпочитать всё равно некого — выбираем из исходных.
  let gated = filterMetal(rows, p.precious);
  if (!gated.length && relax) gated = rows;
  const r = pickByTheme(gated, p.words, single, themed);
  if (!r && gated.length > 1 && !namedSubject(p)) {
    const plain = gated.filter(isPlain);
    if (plain.length === 1) return { id: plain[0].id, conf: 0.6 };
    // Несколько одинаково простых — это дубли одного типа из разных источников: берём тот,
    // на котором уже висят проходы. Но если кандидаты различаются ДВОРОМ, они не дубли, а разные
    // монеты: решать по числу проходов нельзя, иначе «1 рубль 1997 СПМД» уедет на московский тип
    // просто потому, что у него связей больше. Такую ничью отдаём наверх — там сверят двор.
    const oneMint = new Set(plain.map((x) => String(x.mint || ""))).size === 1;
    if (plain.length > 1 && oneMint && (+topOf(plain).links || 0) > 0) return { id: topOf(plain).id, conf: 0.6 };
  }
  if (r || p.precious || !p.words.length) return r;
  // Слова о состоянии, металле и оформлении темой не являются. Без этой оговорки запасной ход
  // ловил «(в специальном исполнении)» и сажал «25 рублей Сочи Факел» на памятного Галилея.
  const th = p.words.filter((w) => !NON_THEME.test(w));
  if (!th.length) return null;
  const hits = rows.filter((row) => {
    const nf = wordsOf((row.name_full || "") + " " + (row.theme_ru || ""));
    return th.some((w) => themeHit(nf, w));
  });
  return hits.length === 1 ? { id: hits[0].id, conf: 0.7 } : null;
}

