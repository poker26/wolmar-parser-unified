const sqlLit = (x) => "'" + String(x).replace(/'/g, "''") + "'";

function denomAlternatives(d) {
  const alts = ["denomination_text ~* $3"];                       // цифрой в начале — основной случай
  const numRe = d.fraction && d.raw ? d.raw.replace("/", " *[/] *") : String(d.num).replace(".", "\\.");
  alts.push(`denomination_text ~* ${sqlLit("[$]" + numRe + "([^0-9]|$)")}`);   // «$25», «PLATINUM $10»
  const en = enUnit(d.unit);
  const word = NUM_WORD[d.num];
  if (word && en) alts.push(`denomination_text ~* ${sqlLit("^" + word + "[ -]+" + en)}`);  // «FIVE DOLLARS»
  if (d.num === 1 && en) alts.push(`denomination_text ~* ${sqlLit("^(ONE +)?" + en + "S?( |$)")}`);
  for (const n of NAMED) if (n.num === d.num && n.unit.test(String(d.unit || ""))) alts.push(`denomination_text ~* ${sqlLit(n.re)}`);
  return alts;
}

// Русские имена стран, собранные ИЗ САМОГО КАТАЛОГА (таблица numis_country_ru): словарь
// numis_country_map знал 228 стран из 699, и «Великобритания» (1622 типа), «Китай» (1273),
// «Бавария» матчеру были неизвестны. Здесь имя сразу указывает на каталожное написание.
// Склонения режем по основе: «Германия»/«Германии» → «Германи».
// Название страны ищем СЛОВОМ, а не подстрокой. Поиск через includes давал тихую катастрофу:
// «эмали» содержит «мали», «лейб-гренадерского» — «гренад», и знаки с медалями уезжали в Мали и
// Гренаду (1838 и 230 лотов соответственно). Допускаем окончание не длиннее трёх букв — столько
// бывает при склонении («Германии», «Пруссию», «Финляндией»), но не «гренадерского».
const reEsc = (x) => String(x).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// Написание имени страны гуляет: «Соединенные Штаты» без ё (592 лота), «Стрейтс-Сетлментс» через
// дефис и «Стрейтс Сеттлментс» через пробел с разным числом «т». Приводим к общему виду и заголовок,
// и словарь: ё к е, дефис к пробелу, двойные согласные к одинарным.
const ruNorm = (x) => String(x || "").toLowerCase().replace(/ё/g, "е").replace(/[-–—]/g, " ")
  .replace(/([бвгджзклмнпрстфхцчшщ])\1/g, "$1").replace(/\s+/g, " ").trim();
const wordRe = (stem) => new RegExp("(?<![а-яa-z])" + reEsc(ruNorm(stem)) + "[а-я]{0,3}(?![а-яa-z])", "i");

const ruStem = (s) => {
  const t = String(s || "").toLowerCase().trim();
  const cut = t.replace(/[аяиыоеёуюйьъ]$/i, "");
  return cut.length >= 5 ? cut : t;
};
let CRU = null;
async function catalogRu(pool) {
  if (!CRU) {
    const rows = (await pool.query("SELECT country, ru FROM numis_country_ru WHERE ru IS NOT NULL")).rows;
    const list = [];
    for (const r of rows) {
      const vars = Array.isArray(r.ru) ? r.ru : [];
      for (const v of vars) {
        const stem = ruStem(v);
        // Мусорные имена вроде «1S;» приходят из плохо разобранных полос справочника и ловят
        // случайные лоты: имя страны — это буквы, а не цифры со знаками.
        // Диакритика — тоже буква: без неё отсев мусора выбрасывал «Württemberg» и «Lübeck».
        if (!/^[A-Za-zА-Яа-яЁёÀ-ɏ][A-Za-zА-Яа-яЁёÀ-ɏ '\-().&]*$/.test(String(r.country || ""))
            || String(r.country).length < 3) continue;
        if (stem.length >= 4) list.push({ stem: ruNorm(stem), country: r.country, re: wordRe(stem) });
      }
    }
    CRU = list.sort((a, b) => b.stem.length - a.stem.length);
  }
  return CRU;
}

// Одна страна живёт в каталоге под разными написаниями: «Kingdom Of Thailand» против «Thailand»,
// «Straits Settlement» против «Straits Settlements», «Congo, Democratic Republic» против
// «Democratic Republic of the Congo». Точный ключ их не сводит, и лот уходил в страну, которой в
// каталоге нет вовсе (одного Таиланда так потерялось 994 лота). Запасной ключ — НАБОР слов имени
// без окончаний множественного числа; названия считаем одной страной, когда набор одного целиком
// входит в набор другого. Подмножество, а не пересечение: у «United Kingdom» и «United States»
// общее слово есть, но ни одно не входит в другое целиком — они не сольются.
const CWORDS = (s) => new Set(String(s || "").toLowerCase().replace(/[^a-z0-9 ]/g, " ").split(/\s+/)
  .filter((w) => w && !/^(of|the|and)$/.test(w)).map((w) => w.replace(/s$/, ""))
  // хвост от апострофа: «People's» распадается на «people» и «s», и одинокая буква мешала
  // сойтись «China, People's Republic» с «China, Peoples Republic»
  .filter((w) => w.length > 1));
// Разница между написаниями допустима только в словах об устройстве государства («Kingdom of
// Thailand» и «Thailand» — одна страна). Слова «republic», «democratic», «peoples», «federal»
// сюда НЕ входят: ими различаются РАЗНЫЕ государства — Тайвань и КНР, ФРГ и ГДР, — и склеивать
// их нельзя.
const CEXTRA = /^(kingdom|state|sultanate|principality|emirate|duchy|grand|dominion|colony|territory|island)$/;
const sameCountry = (a, b) => {
  const [big, small] = a.size >= b.size ? [a, b] : [b, a];
  return [...small].every((w) => big.has(w)) && [...big].filter((w) => !small.has(w)).every((w) => CEXTRA.test(w));
};

let CMAP = null, CATC = null;
async function catalogCountry(pool, en) {
  if (!CATC) {
    CATC = new Map();
    const rows = (await pool.query("SELECT country, count(*)::int c FROM coin_type WHERE era='foreign' AND country IS NOT NULL GROUP BY 1")).rows;
    for (const r of rows) {                       // на коллизии ключа берём написание с бОльшим числом типов
      const k = normCountry(r.country);
      const cur = CATC.get(k);
      if (!cur || cur.c < r.c) CATC.set(k, r);
    }
  }
  const k = normCountry(en);
  const hit = CATC.get(COUNTRY_ALIAS[k] || k) || CATC.get(k);
  if (hit) return hit.country;
  // Точного ключа нет — пробуем сойтись по набору слов и берём написание с бОльшим числом типов.
  const want = CWORDS(en);
  if (want.size) {
    let best = null;
    for (const r of CATC.values()) {
      const have = CWORDS(r.country);
      if (!have.size || !sameCountry(want, have)) continue;
      if (!best || best.c < r.c) best = r;
    }
    if (best) return best.country;
  }
  return tc(en);                                 // такой страны в каталоге нет вовсе (совпадений не будет)
}
// Из нескольких совпавших стран выбираем ту, у которой в каталоге меньше типов: земля всегда
// меньше государства, а значит точнее. Счёт типов уже собран в CATC при первом обращении.
async function narrowest(pool, names) {
  let best = null, bc = Infinity;
  for (const n of names) {
    const r = (await pool.query(
      "SELECT count(*)::int c FROM coin_type WHERE era='foreign' AND country=$1", [n])).rows[0];
    if (r.c && r.c < bc) { bc = r.c; best = n; }
  }
  return best || names[0];
}

// Одна страна разложена в каталоге на эпохи: «China» (империя и республика) и «China, People's
// Republic», «Germany» и «Germany - Federal Republic». Русское имя «Китай» ведёт на одну из них,
// и лот 1908 года попадал в раздел КНР, где типов с 1956 — кандидатов ноль. Если у выбранной
// страны нет НИ ОДНОГО типа на год лота, ищем соседний раздел той же страны и берём его.
// Соседним считаем только тот, чьё имя содержит имя выбранной страны или содержится в нём:
// «Korea-North» и «Korea-South» так не спутаются, а «China» и «China, People's Republic» сойдутся.
async function eraSection(pool, country, year) {
  if (!country || !year) return country;
  const cnt = async (c) => (await pool.query(
    `SELECT count(*)::int c FROM coin_type WHERE era='foreign' AND country=$1
       AND $2 BETWEEN COALESCE(year_start, year) AND COALESCE(year_end, year)`, [c, year])).rows[0].c;
  if (await cnt(country)) return country;
  const lc = country.toLowerCase();
  const sibs = [...CATC.values()]
    .filter((r) => r.country !== country &&
      (r.country.toLowerCase().includes(lc) || lc.includes(r.country.toLowerCase())))
    .sort((a, b) => b.c - a.c);
  for (const s of sibs) if (await cnt(s.country)) return s.country;
  return country;
}

// Возвращает СПИСОК стран-кандидатов в порядке упоминания. Выбирать заранее нельзя: в заголовке
// страна встречается и как эмитент, и как часть сюжета — «Острова Кука 2012, 20 долларов. Бегство
// в Египет» или «1 доллар 2013 Ниуэ. День столицы Казахстан Астана». Кто из них эмитент, знает
// каталог: тот, в чьём разделе есть тип с таким номиналом и годом. Поэтому решение принимает не
// этот разбор, а перебор в matchForeignByCountry.
async function countryList(pool, title, year = null, unit = null) {
  if (!CMAP) {
    const rows = (await pool.query("SELECT ru,en FROM numis_country_map WHERE en IS NOT NULL")).rows
      .map((r) => ({ ru: r.ru, en: RU_OVERRIDE[r.ru] || r.en }))
      .concat(RU_EXTRA.map(([ru, en]) => ({ ru, en })));
    CMAP = rows.sort((a, b) => b.ru.length - a.ru.length).map((r) => ({ ...r, ruLc: ruNorm(r.ru), re: wordRe(r.ru) }));
  }
  const t = ruNorm(title);    // заголовки на маркетплейсе часто КАПСОМ — сравниваем без регистра
  // В заголовке называют и государство, и его землю: «20 марок. Германия. Пруссия 1900». Тип в
  // каталоге лежит под землёй (Prussia), а не под государством, поэтому из всех совпавших имён
  // берём САМОЕ УЗКОЕ — то, у которого в каталоге меньше типов. Одиночное совпадение проходит
  // прежним путём и ничего не стоит.
  // Собираем ВСЕ совпавшие имена вместе с их местом в строке. Место важно: «Северная Корея»
  // содержит внутри себя «Корея», и это ОДНО упоминание — брать надо длинное. А «Германия» и
  // «Пруссия» в «20 марок. Германия. Пруссия 1900» стоят в разных местах: это два разных
  // упоминания, и тогда точнее земля.
  // Название единицы номинала страной не является. Основа «Марокко» усекается до «марок», и
  // «5 марок 1936 Гинденбург» — германская монета — определялась как Марокко; так же «5 крон»
  // рискует поймать Хорватию (куна). Совпадение, которое целиком является единицей номинала,
  // отбрасываем — это то же правило, что «единица номинала не бывает сюжетом».
  // Сверяем ТОЧНЫМ равенством с единицей самого лота: «5 марок» — единица «марок», и совпадение
  // «марок» это она. Страна «Марокко» нормализуется в «мароко» и равенства не даёт, поэтому
  // «Марокко, 10 франков» по-прежнему определяется верно.
  const un = unit ? ruNorm(unit) : null;
  const isUnit = (w) => !!un && ruNorm(w) === un;
  // Имена берём ИЗ ОБОИХ словарей сразу — курируемого и собранного из каталога. Раньше второй был
  // запасным и включался, только если первый промолчал: «3 марки. Германия. Вюртемберг 1911»
  // находило «Германию» в курируемом, на этом останавливалось и до «Вюртемберга» не доходило —
  // хотя тип лежит именно под ним. Так же терялись Ганновер, Любек, Гессен-Кассель, а «Османская
  // империя» уезжала в нынешнюю Турцию.
  const found = [];
  for (const r of CMAP) { const m = r.re.exec(t); if (m && !isUnit(m[0])) found.push({ en: r.en, at: m.index, len: m[0].length }); }
  for (const r of await catalogRu(pool)) {
    const m = r.re.exec(t);
    if (m && !isUnit(m[0])) found.push({ en: r.country, at: m.index, len: m[0].length });
  }
  const outer = found.filter((h) => !found.some((o) => o !== h && o.at <= h.at && o.at + o.len >= h.at + h.len && o.len > h.len));
  if (outer.length) {
    const names = [];
    for (const h of outer.sort((a, b) => a.at - b.at)) names.push(await catalogCountry(pool, h.en));
    const uniq = [...new Set(names)];
    const era = [];
    for (const n of uniq) era.push(await eraSection(pool, n, year));
    return [...new Set(era)];
  }
  // Курируемый словарь молчит — пробуем имена, собранные из каталога (они уже в его написании).
  for (const r of await catalogRu(pool)) {
    const m = r.re.exec(t);
    if (m && !isUnit(m[0])) return [await eraSection(pool, await catalogCountry(pool, r.country), year)];
  }
  return [];
}

// Диагностика: куда девается лот, который не привязался. На поведение не влияет — заполняется,
// только если снаружи выставили DIAG.on (см. catalog/census-misses.js).
const DIAG = { on: false, reason: null, n: 0 };
const why = (r, n) => { if (DIAG.on) { DIAG.reason = r; DIAG.n = n || 0; } return null; };

async function matchType(pool, p) {
  if (DIAG.on) { DIAG.reason = null; DIAG.n = 0; }
  if (p.isSet) return why("набор");
  if (p.isNonCoin) return why("не монета");
  if (!p.denom) return why("номинал не разобран");
  if (!p.year) return why("год не разобран");
  const d = p.denom;
  // Рубль и копейку чеканила не только Россия: у Беларуси и Приднестровья свой рубль и своя
  // копейка, у Украины копейка, у Таджикистана и Латвии рубль ходил в девяностых. Если такая
  // страна названа в заголовке, в русские типы не идём — «1 рубль 2009 Беларусь» садился на нашу
  // ходячку. Список именно точечный: запрет «названа любая страна» отрезал бы «100 рублей. Победа
  // над Японией», где страна лишь часть сюжета.
  const RUB_STATES = /^(Belarus|Transnistria|Ukraine|Tajikistan|Latvia|Lithuania|Moldova)$/i;
  if (d.isRf && d.textOnly) {
    // Номинал записан словом и рублёвого значения не имеет: ищем по тексту номинала и году,
    // эру берём у найденного типа — червонцы есть и имперские, и советские, и у ЦБ.
    const rows = (await pool.query(
      `SELECT id, name_full, metal, theme_ru, era, mint,
              (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links
         FROM coin_type WHERE year=$1 AND (denomination_text ILIKE $2 OR name_full ILIKE $2)`,
      [p.year, "%" + d.unit + "%"])).rows;
    const r = pickWithMetal(rows, p, 0.7, 0.85, true);
    if (!r) return why("номинал словом: не выбрать", rows.length);
    const hit = rows.find((x) => x.id === r.id);
    return { ...r, era: hit && hit.era ? hit.era : "modern" };
  }
  if (d.isRf) {
    if (d.value == null) return why("номинал без рублёвого значения");
    const own = String((await countryList(pool, p.title, p.year, p.denom && p.denom.unit))[0] || "");
    if (RUB_STATES.test(own)) return await matchForeignByCountry(pool, p, own);
    if (p.year < 1917) {                                  // ИМПЕРСКОЕ: двор-дизамбиг
      // Номер по Биткину бьёт все прочие признаки: он и есть точное указание на разновидность.
      // Номер не уникален в каталоге (у 472 номеров по два типа, у 168 по три) — это дубли одной
      // монеты из разных источников, ничью решаем как обычно, числом уже привязанных лотов.
      if (p.bitkin) {
        // Номер сверяем ВМЕСТЕ с номиналом и двором, а не вместо них. Иначе опечатка продавца в
        // номере (или номер из чужого издания) перебивает то, что прямо написано в заголовке:
        // «3 копейки 1876 СПБ» уезжало на «5 копеек 1876 СПБ», «2 копейки 1853 ЕМ» — на «ВМ».
        const byNum = (await pool.query(
          `SELECT id, name_full, mint,
                  (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links
             FROM coin_type WHERE era='imperial' AND bitkin_number=$1 AND ($2::int IS NULL OR year=$2)
               AND ROUND(denomination_value,6)=ROUND(CAST($3 AS numeric),6)`,
          [p.bitkin, p.year, String(d.value)])).rows;
        const marks0 = titleMarks(p.title);
        const fit = marks0 ? byNum.filter((r) => markScore(r.mint, marks0) >= 0) : byNum;
        const byNumTop = fit.length ? topOf(fit) : null;
        if (byNumTop && variantOk(byNumTop, p)) return { id: byNumTop.id, conf: 0.95, era: "imperial" };
      }
      // Черновые типы (status='draft') в ОБЩИЙ отбор не входят: это заготовки точных вариантов
      // Биткина, и без ссылки в описании они лишь размывают пул одинаковых кандидатов. По ссылке
      // (ветка выше) они находятся, потому что там отбор идёт по самому номеру.
      const all = (await pool.query("SELECT id, name_full, metal, theme_ru, mint, (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links FROM coin_type WHERE era='imperial' AND status IS DISTINCT FROM 'draft' AND ROUND(denomination_value,6)=ROUND(CAST($1 AS numeric),6) AND year=$2", [String(d.value), p.year])).rows;
      let rows = filterMetal(all, p.precious);
      if (rows.length === 1 && variantOk(rows[0], p)) return { id: rows[0].id, conf: 0.7, era: "imperial" };
      // ⚠️ Каждый прямой возврат ниже обязан пройти проверку разновидности: лот, который называет
      // перечекан, новодел или инкузность, не может сесть на тиражный тип. Отбор по двору её
      // раньше обходил, и такие лоты подмешивались в ценовую корзину тиражного типа.
      const marks = titleMarks(p.title);
      if (rows.length > 1 && marks) {
        const scored = rows.map((r) => [r, markScore(r.mint, marks)]).filter(([, sc]) => sc >= 0);
        const top = Math.max(0, ...scored.map(([, sc]) => sc));
        const f = scored.filter(([, sc]) => sc === top).map(([r]) => r);
        if (top > 0 && f.length === 1 && variantOk(f[0], p)) return { id: f[0].id, conf: 0.85, era: "imperial" };
        if (f.length) rows = f;
      }
      rows = plainVariants(rows.length ? rows : all, p);
      // Разновидности отсеяны — и выбирать больше не из чего.
      if (rows.length === 1 && variantOk(rows[0], p)) return { id: rows[0].id, conf: 0.7, era: "imperial" };
      // Двор в заголовке не назван (а бывает и прямо сказано «монетный двор не определён»).
      // Тогда монете отвечает ТИРАЖНЫЙ тип без двора, а не любой из дворовых: приписать лот
      // конкретному двору мы не вправе, а держать его сиротой — терять проход впустую.
      // Именно ДВОР, а не любой знак: инициалы минцмейстера («ВС», «АГ») двора не называют, и
      // пустой список знаков в JavaScript истинен — обе оговорки нужны, иначе запасной ход молчит.
      if (!marks || !marks.some((m) => MINT_TOKEN.test(m))) {
        const nomint = rows.filter((x) => !x.mint);
        const nm = topOf(nomint);
        if (nomint.length && variantOk(nm, p)) return { id: nm.id, conf: 0.65, era: "imperial" };
      }
      const r = pickWithMetal(rows, p, 0.65, 0.8, true);
      return r ? { ...r, era: "imperial" } : why(all.length ? "имперское: не выбрать" : "имперское: нет типа", (rows.length || all.length));
    }
    if (p.year <= 1991) {                                 // СССР: погодовка/памятные
      let rows = (await pool.query("SELECT id, name_full, metal, theme_ru, (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links FROM coin_type WHERE era='ussr' AND denomination_value=$1 AND year=$2", [d.value, p.year])).rows;
      // relax тот же, что в имперской ветке: серебро СССР (полтинник, рубль 1924, биллон 500-й)
      // это норма номинала, а не дорогой тёзка, и в заголовке металл называют не всегда.
      rows = plainVariants(rows, p);
      // Разновидности штемпеля из описаний wolmar («15 копеек 1925. Лицевая сторона - 1.11.,
      // оборотная сторона…», «50 копеек 1922. ПЛ») стоят в каталоге рядом с тиражным типом, и
      // различить их нечем, если лот о разновидности молчит. Оставляем ту, чьё уточнение лот
      // ОБЪЯСНЯЕТ; если ни одна не объяснена — тиражную.
      if (rows.length > 1) {
        // Уточнение штемпеля, а не сюжета: «Лицевая сторона - 1.11., оборотная сторона…»,
        // «шт. 1.12», «вариант расположения узелков». Именно им отличаются разновидности одной
        // монеты. Имя человека или города («1 рубль. Я. Райнис») сюда не относится — это другая
        // монета, и подменять её тиражным типом нельзя.
        const DIE_QUAL = /(сторона|штемпел|(?<![а-яё])шт\.|вариант|узелк|разновидност)/i;
        const qualOf = (n) => { const i = String(n || "").indexOf(". "); return i < 0 ? "" : String(n).slice(i + 2); };
        const head = p.headWords && p.headWords.length ? p.headWords : p.words;
        const die = rows.filter((x) => DIE_QUAL.test(qualOf(x.name_full)));
        if (die.length && die.length < rows.length) {
          // Разновидность различает НОМЕР штемпеля («шт. 1.12» против «1.11»), а не слова:
          // «лицевая сторона» есть у каждой. Совпал номер — это она; не совпал ни у одной —
          // лот про разновидность, которой в каталоге нет, и отвечает ему тиражный тип.
          const nums = (x) => String(x || "").match(/\d+\.\d+/g) || [];
          const lotNums = nums(String(p.title || "").split("|")[0]);
          const explained = lotNums.length
            ? die.filter((x) => nums(qualOf(x.name_full)).some((n) => lotNums.includes(n)))
            : [];
          rows = explained.length ? explained : rows.filter((x) => !die.includes(x));
        }
      }
      if (rows.length === 1 && variantOk(rows[0], p)) return { id: rows[0].id, conf: 0.7, era: "ussr" };
      const r = pickWithMetal(rows, p, 0.65, 0.8, true);
      return r ? { ...r, era: "ussr" } : why(rows.length ? "СССР: не выбрать" : "СССР: нет типа", rows.length);
    }
    let rows = (await pool.query("SELECT id, name_full, metal, theme_ru, mint, (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links FROM coin_type WHERE era IS NULL AND country='RU' AND denomination_value=$1 AND (year=$2 OR coin_year=$2)", [d.value, p.year])).rows;
    // Сначала тема, и только потом двор. Обратный порядок уже дал промах: у «25 рублей Сочи
    // Факел 2014 СПМД» отбор по двору оставил единственным кандидатом памятную монету Галилею,
    // и она была выбрана как безальтернативная. Двор решает лишь среди ТИРАЖНЫХ типов, где
    // различать больше нечем.
    // Серия, в которой несколько типов носят ОДНО имя (у ЦБ так оформлены города-герои и
    // министерства: различаются только двором), не даёт различить монеты. Считаем это ДО отбора по
    // двору — иначе после него остаётся один кандидат и неоднозначность становится невидимой.
    // Состав ДО отбора по двору — по нему и считаем, есть ли у победителя тёзка.
    const rows0 = rows.slice();
    // Двор, названный в заголовке, — жёсткий признак: тип с ДРУГИМ двором это другая монета.
    // «3 рубля. Партизанское движение 1994 ММД» садилось на ленинградский тип. Кандидатов без
    // указанного двора не трогаем — они ничему не противоречат.
    if (p.modMints.length) {
      rows = rows.filter((x) => !x.mint || p.modMints.includes(MOD_CANON[String(x.mint).trim()] || x.mint));
      if (!rows.length) return why("модерн-РФ: нет типа");
    }
    // Спецверсия («в специальном исполнении», цветная, с позолотой) — другой товар и другая цена.
    // Если лот о ней молчит, речь об обычной монете: два типа с одним сюжетом различить больше
    // нечем, и матчер воздерживался («3 рубля. Петергоф 2015» при готовых обоих типах).
    const SPECIAL = /(в +специальном +исполнении|цветн|позолоч|позолот|с +бриллиант)/i;
    if (rows.length > 1) {
      const want = SPECIAL.test(p.title);
      const f = rows.filter((x) => SPECIAL.test(String(x.name_full || "") + " " + String(x.theme_ru || "")) === want);
      if (f.length) rows = f;
    }
    let r = pickWithMetal(rows, p);
    // В такой серии привязка возможна, только если в заголовке нет слова, которого нет у типа:
    // «Москва» и «Смоленск» в каталоге не записаны, и выбрать между ними нечем.
    // Правило нужно только пока у типов серии НЕТ различающего сюжета. Как только он появился
    // (в theme_ru прочитана «Москва» или «Министерство финансов»), выбор делается по нему, и
    // требовать объяснения всех прочих слов заголовка незачем.
    // Неоднозначность считаем ДЛЯ ПОБЕДИТЕЛЯ, а не для всего пула: пара тёзок где-то сбоку
    // («1 рубль» московского и питерского чекана) не должна требовать объяснения слов у
    // «1 рубль. Фламинго» — из-за этого «Красная книга ФЛАМИНГО» не находила своего фламинго.
    const win = rows0.find((x) => x.id === (r || {}).id);
    const winAmbiguous = !!win && rows0.filter((x) =>
      String(x.name_full || "").toLowerCase().trim() === String(win.name_full || "").toLowerCase().trim()).length > 1;
    if (r && winAmbiguous && !String((win || {}).theme_ru || "").trim()) {
      const row = win;
      const known = wordsOf((row && row.name_full) + " " + ((row && row.theme_ru) || ""));
      // Слова берём ГОЛОВНЫЕ (до «|»), а не все: там продавец называет монету, а дальше идёт его
      // проза — «В слабе NGC», «Справа — архитектурная композиция». По всем словам правило
      // срабатывало на каждом подробно описанном лоте, и «Боевая башня "Вовнушки"» не находила
      // собственный тип, хотя тот лежал в кандидатах.
      const check = (p.headWords && p.headWords.length ? p.headWords : p.words);
      if (check.filter((w) => !NON_THEME.test(w)).some((w) => !themeHit(known, w))) r = null;
    }
    // Запасной ход по двору годится ТОЛЬКО для монеты без названного сюжета. Иначе «10 рублей.
    // 70 лет Победы. Перекуем мечи на орала» и «2 рубля. Москва. 55-я годовщина Победы» ложились
    // на тиражные типы спайна и снова собирали смешанную ценовую корзину — мимо всех проверок,
    // сделанных выше.
    if (!r && !namedSubject(p)) {
      const plain = rows.filter(isPlain);
      let byMint = p.modMints.length
        ? plain.filter((x) => p.modMints.includes(MOD_CANON[String(x.mint || "").trim()] || x.mint))
        : [];
      // Двор не назван — или назван, но отдельного типа под него нет (в спайн он не попал по
      // редкости): общий тиражный тип без двора подходит и в том, и в другом случае.
      if (!byMint.length) byMint = plain.filter((x) => !x.mint);
      if (byMint.length) r = { id: topOf(byMint).id, conf: 0.65 };
    }
    if (r) return { ...r, era: "modern" };
    // Год выпуска по каталогу ЦБ и год НА МОНЕТЕ расходятся: серию «Чемпионат мира по футболу
    // FIFA 2018» банк выпускал в 2016-2017, а продавцы пишут 2018 — и все 883 таких лота висели
    // сиротами при полностью готовых типах. Ищем в соседних годах, но принимаем ТОЛЬКО уверенное
    // совпадение по сюжету: у обиходной монеты сюжета нет, и разные годы она не перепутает.
    const near = (await pool.query(
      `SELECT id, name_full, metal, theme_ru, mint,
              (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links
         FROM coin_type WHERE era IS NULL AND country='RU' AND denomination_value=$1
           AND year BETWEEN $2 - 1 AND $2 + 1 AND year <> $2`, [d.value, p.year])).rows;
    const rn = near.length ? pickWithMetal(near, p) : null;
    if (rn && rn.conf >= 0.8) return { ...rn, era: "modern" };
    return why(rows.length ? "модерн-РФ: не выбрать" : "модерн-РФ: нет типа", rows.length);
  }
  // ТЕРРИТОРИИ ИМПЕРИИ. Финляндия (пенни, марка, с 1864) и Царство Польское (грош, злотый,
  // с 1815) чеканили собственный номинал, но по коллекционерской традиции это русские монеты —
  // и в каталоге они лежат в имперской эре. Ищем их там по ТЕКСТУ номинала: рублёвого значения
  // у таких типов нет намеренно (1 пенни формально равен полушке и склеился бы с русским типом).
  // Германскую марку сюда пускать нельзя, поэтому требуем, чтобы страна лота не была распознана
  // как чужая: подходит только Финляндия, Польша, Россия или отсутствие страны в заголовке.
  const TERR_UNIT = /^(пенни|марк|грош|злот)/;
  const FOR_TERR = /для +(финлянд|польш|пруссии|царства +польского)|молдов[аыи] +и +валахи/i;
  // Нижняя граница 1750, а не 1815: под Польшу её хватало, но прусские монеты русской чеканки
  // (занятая Пруссия при Елизавете) датируются 1759-1762 и в диапазон не попадали.
  if (p.year && p.year >= 1750 && p.year <= 1917 && TERR_UNIT.test(String(d.unit || ""))) {
    const cen = (await countryList(pool, p.title, p.year, p.denom && p.denom.unit))[0] || null;
    // «Для Финляндии», «Для Пруссии», «Для Польши» — прямое указание, что монету чеканила Россия
    // для своей территории или занятой земли; по коллекционерской традиции это русские монеты.
    // Без этой оговорки распознанная чужая страна закрывала им путь в имперскую эру, и все 122
    // прусских лота висели сиротами при наличии типов («1 грош. Пруссия 1759»).
    if (!cen || /^(Finland|Poland|RU|Russia)$/.test(cen) || FOR_TERR.test(p.title)) {
      const numStr = String(d.num).replace(".", "\\.");
      // Единицу ищем и по-русски, и по-английски: финляндские типы пришли из Краузе и записаны
      // «10 PENNIA», «2 MARKKAA», а год у них лежит ДИАПАЗОНОМ чеканки, а не одним числом —
      // при сверке «year=год лота» ни одна финская монета не находилась вовсе.
      const enT = enUnit(d.unit);
      const unitAlt = String(d.unit).slice(0, 4) + (enT ? "|" + numStr + " *" + enT : "");
      let rows = (await pool.query(
        `SELECT id, name_full, metal, theme_ru, denomination_text, issuer,
                (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links
           FROM coin_type
          WHERE era='imperial'
            AND $1 BETWEEN COALESCE(year_start, year) AND COALESCE(year_end, year)
            AND denomination_text ~* $2`,
        [p.year, "^" + numStr + " *(" + unitAlt + ")"])).rows;
      // Территорию в названии типа пишут в именительном («1 грош. Пруссия»), а в заголовке лота
      // она склоняется («Для Пруссии»), и сравнение по целому слову не срабатывало. Сверяем по
      // основе — тем же способом, что и имена стран.
      const terr = (p.title.match(FOR_TERR) || [])[1];
      if (terr && rows.length > 1) {
        const st = ruStem(terr);
        const f = rows.filter((r) => ((r.name_full || "") + " " + (r.denomination_text || "") + " " + (r.issuer || ""))
          .toLowerCase().includes(st));
        if (f.length) rows = f;
      }
      const r = pickWithMetal(rows, p, 0.65, 0.8, true);
      if (r) return { ...r, era: "imperial" };
      if (DIAG.on) why(rows.length ? "имперское: не выбрать" : "имперское: нет типа", rows.length);
    }
  }
  // FOREIGN: страна+год+ведущее число (единица м.б. экзотическая/неизвестная). Граница номинала —
  // «^<num>(не-цифра|конец)», чтобы «10» не ловило «100». Единицу НЕ сверяем (даласи/бутут… не в словаре).
  // Перебираем страны в порядке упоминания и отдаём первое совпадение: эмитента определяет то,
  // у кого в разделе нашёлся нужный номинал за нужный год.
  const cands = await countryList(pool, p.title, p.year, p.denom && p.denom.unit);
  if (!cands.length) return why("страна не распознана");
  let last = null;
  for (const cen of cands) {
    const r = await matchForeignByCountry(pool, p, cen);
    if (r) return r;
    if (DIAG.on) last = DIAG.reason;
  }
  return why(last || "иностранный: не сошлось");
}

// Имя страны темой не является — ровно по той же причине, что и название номинала: оно есть у
// каждого кандидата этой страны. Без этой оговорки «20 рублей. Беларусь 2023. Год Дракона» ловился
// на тип «История банков Беларуси» словом «Беларусь».
async function countryStems(pool, cen) {
  const key = "cs|" + cen;
  if (!memoCS.has(key)) {
    const set = new Set();
    for (const w of String(cen).toLowerCase().match(/[a-z]{4,}/g) || []) set.add(w.slice(0, 5));
    for (const r of await catalogRu(pool)) if (r.country === cen) set.add(r.stem.slice(0, 5));
    for (const r of CMAP || []) if (r.en && String(r.en).toLowerCase() === String(cen).toLowerCase()) set.add(r.ruLc.slice(0, 5));
    memoCS.set(key, set);
  }
  return memoCS.get(key);
}
const memoCS = new Map();

// Есть ли у иностранного типа СЮЖЕТ. У Краузе он идёт после тире («PENNY. UNITED KINGDOM —
// Britannia seated right») либо лежит в русской теме. Если сюжета нет, тип описывает обычную
// монету номинала и года — таких «пустых» кандидатов на одну монету бывает несколько: это дубли
// из описаний аукциона, различающиеся только формой слова («10 сен» и «10 сенов»).
const hasSubject = (row) => /[—–]/.test(String(row.name_full || "")) || !!String(row.theme_ru || "").trim();

// Поиск среди иностранных типов по уже известной стране.
async function matchForeignByCountry(pool, p, cen) {
  const d = p.denom;
  const cs = await countryStems(pool, cen);
  p = { ...p, words: p.words.filter((w) => !cs.has(w.slice(0, 5))) };
  // Краузе печатает единичный номинал ОДНИМ СЛОВОМ: «DOLLAR», «CROWN», «THALER», «PENNY» —
  // без цифры. Таких типов в каталоге 16 430, и требование ведущего числа делало их невидимыми.
  // Поэтому для номинала «1» принимаем и запись без цифры; для остальных — как было.
  // Дробные типы («1/2 DOLLAR») исключаем, если сам лот не дробный, иначе «1 доллар» садится на половину.
  // У дробного номинала ведущее число — сама дробь: «1/13», а не 0.0769.
  const lead = d.fraction && d.raw ? d.raw.replace("/", " *[/] *") : String(d.num).replace(".", "\\.");
  const denomRe = "^" + lead + "([^0-9]|$)";
  // ...но принимать ЛЮБУЮ бесцифровую запись нельзя: под «1» попадут разом DOLLAR, HALF DOLLAR и
  // TWENTY DOLLARS, кандидатов станет много и матчер воздержится. Поэтому сверяем ЕДИНИЦУ:
  // «1 доллар» ищет «DOLLAR»/«ONE DOLLAR», а не всё подряд.
  const denomCond = "(" + denomAlternatives(d).join(" OR ") + ")";
  const fracGuard = d.fraction ? "" : " AND denomination_text !~ '^[0-9]+ *[/] *[0-9]'";
  // Тип Краузе — это KM#, а не отдельный год: одна строка каталога покрывает весь период чеканки
  // (Пруссия KM#481 — 1861-1873), и в колонке year лежит только ПЕРВЫЙ год. Сверка по нему теряла
  // лоты всех остальных годов, а таких типов в спайне 10 тысяч. Ищем попадание года В ДИАПАЗОН,
  // а где диапазона нет — по-прежнему точное совпадение.
  let rows = (await pool.query(
    `SELECT id, name_full, country, metal, theme_ru, mass, denomination_text,
              (SELECT count(*)::int FROM lot_type_link l WHERE l.type_id=coin_type.id) links
       FROM coin_type WHERE era='foreign' AND country=$1
       AND $2 BETWEEN COALESCE(year_start, year) AND COALESCE(year_end, year)
       AND ${denomCond}${fracGuard}`, [cen, p.year, denomRe])).rows;
  // Единицу номинала СВЕРЯЕМ, когда знаем её английское имя. Раньше сверялось только ведущее
  // число, и «10 фунтов» получал в кандидаты «10 PENCE», «5 долларов» — «5 CENTS», а
  // «1/2 соверена» — «1/2 PENNY». Кандидатов набиралось по десятку, различить их было нечем, и
  // матчер воздерживался. Экзотические единицы (даласи, бутут) в словаре не значатся — там
  // по-прежнему решает число.
  const en = enUnit(d.unit);
  // Единицу, которой нет в словаре, раньше НЕ сверяли вовсе — оставалось только совпадение числа,
  // и лот садился на чужую единицу того же номера: «10 миллимов. Тунис» → «10 DINARS», «1 ранд.
  // ЮАР» → «1 CENT», «2 пенго. Венгрия» → «2 FILLÉR». Сверяем транслитерацией: у заимствованных
  // единиц русское написание фонетическое, и «миллимов»/«MILLIM», «даласи»/«DALASIS» сходятся.
  if (!en && rows.length) {
    const want = unitSkeleton(d.unit);
    if (want.length >= 3) {
      const f = rows.filter((x) => {
        const w = String(x.denomination_text || "").match(/[A-Za-zА-Яа-яЁёÀ-ɏ]{3,}/);
        if (!w) return true;                       // у типа единица не написана — не противоречит
        const have = unitSkeleton(w[0]);
        const n = Math.min(4, want.length, have.length);
        return n >= 3 && want.slice(0, n) === have.slice(0, n);
      });
      if (!f.length) return why("единица номинала не совпала", rows.length);
      rows = f;
    }
  }
  // Проверяем единицу и когда кандидат ОДИН: единственный кандидат с чужой единицей — это не
  // «выбирать не из чего», а «подходящего типа нет». Так «1/2 доллара. США 1972» садилось на
  // «1/2 PENNY», а «1 крона. Великобритания» — на «1 CENT».
  if (en && rows.length) {
    // Единицу пишут и по-английски («2 MARK»), и по-русски — у типов, собранных из описаний
    // аукциона, она русская («2 марки»). Принимаем оба написания, иначе фильтр выбрасывает
    // ровно тот тип, на котором лот и должен был сойтись.
    const re = new RegExp("(?<![A-Z])" + en + "S?(?![A-Z])", "i");
    const ru = new RegExp("(?<![а-яё])" + String(d.unit).slice(0, 4) + "[а-яё]*(?![а-яё])", "i");
    // Единицу печатают и составным словом: «5 REICHSMARK», «5 RENTENMARK», «5 REICHSPFENNIG».
    // Строгая граница слева их отвергала, и все немецкие монеты тридцатых годов оставались без
    // типа. Приставку допускаем ТОЛЬКО в поле номинала: в имени типа стоит страна, и «MARK»
    // нашлось бы внутри «DENMARK», перетащив к маркам датские кроны.
    // Приставка допускается ТОЛЬКО из известных уточнителей. Обобщённая («любые 3-9 букв»)
    // пропускала «KRUGERRAND» как «RAND», и «1 ранд. ЮАР» садился на золотой крюгерранд.
    const cmp = new RegExp("(?<![A-Z])(?:REICHS|RENTEN|DEUTSCHE|GOLD|SILBER|NEUE?|NEW|OLD|NOVA?)" + en + "S?(?![A-Z])", "i");
    const f = rows.filter((x) => {
      const dt = String(x.denomination_text || "");
      const txt = dt + " " + String(x.name_full || "");
      return re.test(txt) || ru.test(txt) || cmp.test(dt);
    });
    // Ни один кандидат не совпал по единице — значит подходящего типа среди них нет. Раньше в этом
    // случае список оставляли целиком, и «1/2 доллара. США 1972» садилось на «1/2 PENNY»,
    // «50 центов. Австралия» — на «50 пенсов», «5 пенни. Финляндия» — на «5 MARKKAA».
    if (!f.length) return why("единица номинала не совпала", rows.length);
    rows = f;
  }
  // Названный в лоте драгоценный металл — не только защита от дешёвого тёзки, но и признак
  // выбора: у «5 долларов. Ниуэ 2009г. Au» среди кандидатов и серебро, и золото.
  // Историческое государство, названное в лоте, — жёсткий признак: тип другого государства это
  // другая монета. Пусто после отсева — значит подходящего типа нет, и мы воздерживаемся.
  const issuerPattern = historicalIssuerPattern(p.title);
  if (issuerPattern && rows.length) {
    rows = rows.filter((x) => issuerPattern.test(`${x.country || ""} ${x.name_full || ""} ${x.theme_ru || ""}`));
    if (!rows.length) return why("историческое государство не совпало");
  }
  const want = lotMetal(p.title);
  if (want && rows.length > 1) {
    const f = rows.filter((x) => want.test(String(x.metal || "")));
    if (f.length) rows = f;
  }
  // Вес из описания («Au 3,14», «серебро 31,1 гр») различает то, что не различает ничто другое:
  // у «15 долларов. Австралия 2005» четыре золотых кандидата одного номинала и года, и отличаются
  // они именно весом. Допуск 3% — на разнобой в округлении справочников.
  // ⚠️ Сейчас признак БЕЗДЕЙСТВУЕТ: coin_type.mass у иностранных типов пуст у всех 90 тысяч, а в
  // текстовом слое разобранных томов Краузе веса нет вовсе (проверено по coin_ref_raw). Условие
  // оставлено, чтобы заработать сразу, как только вес появится, — но пока это не признак.
  const gr = lotMass(p.title);
  if (gr && rows.length > 1) {
    const f = rows.filter((x) => x.mass != null && Math.abs(+x.mass - gr) / gr < 0.03);
    if (f.length) rows = f;
  }
  let r = pickWithMetal(rows, p);
  // Тема не различила. Если среди кандидатов есть типы БЕЗ сюжета, лот описывает обычную монету, а
  // не памятную: берём такой тип, а среди нескольких — тот, на котором уже висят проходы. Это то же
  // правило, что для русских эр («тиражный тип по умолчанию»), просто сюжет у Краузе оформлен иначе.
  if (!r && rows.length > 1 && !namedSubject(p, cs)) {
    const plain = rows.filter((x) => !hasSubject(x));
    if (plain.length) r = { id: topOf(plain).id, conf: 0.6 };
  }
  // Уцелел РОВНО ОДИН кандидат — страна, год, номинал и его единица уже сошлись, выбирать больше
  // не из чего. Раньше такой тип всё равно отвергался, если у него в справочнике записан рисунок
  // («10 BANI. MOLDOVA — Номинал, дата и монограмма»): сверка шла с сюжетом, а у Краузе в этом
  // поле ОПИСАНИЕ ШТЕМПЕЛЯ, которого продавец в заголовке не пишет и писать не должен.
  // Условие «в лоте не названо имя собственное» оставляет прежнюю защиту: если продавец назвал
  // сюжет, а единственный кандидат про него молчит, это разные монеты и мы по-прежнему молчим.
  if (!r && rows.length === 1 && !namedSubject(p, cs) && variantOk(rows[0], p)) r = { id: rows[0].id, conf: 0.6 };
  if (r) return { ...r, era: "foreign" };
  return why(rows.length ? "не выбрать из кандидатов" : "нет типа в каталоге", rows.length);
}

